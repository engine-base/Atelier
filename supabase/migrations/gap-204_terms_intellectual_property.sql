--
-- 経営者の依頼「AI があるとデザインや HTML/CSS を真似して作られる。
-- どうにかできないか」への対応のうち、**法務面**の部分。
--
-- 技術的な事実として、ブラウザへ配った HTML/CSS/JS は必ず相手の手元に届き、
-- 届いたものは読める。**見た目の模倣を技術で止めることはできない**。
-- そこで「技術で守るもの」と「法で守るもの」を分けた:
--
--   技術で守る (GAP-204 の Gate #16):
--     プロンプト・スキル本文・テンプレ本文が画面側 JS に混ざらないことを機械検査
--   法で守る (この migration):
--     複製・翻案・リバースエンジニアリング・競合サービスへの利用の禁止
--     機械学習の学習データとしての利用の禁止
--     ユーザー自身の成果物は対象外であることの明示 (過剰な権利主張をしない)
--
-- ⚠️ 本文は **法務レビュー前のドラフト**。GAP-188 と同じ扱いで、確定文言は
--    法務レビュー後に新 version 行で差し替える (旧版は残し is_current のみ更新)。
--    docs/gap-backlog.md の「規約の法務レビューと再同意」と同じ塊で扱うこと。

