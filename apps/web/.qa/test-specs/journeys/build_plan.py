def R(
    id,
    order,
    role,
    phase,
    cond,
    branch,
    dep,
    action,
    steps,
    expected,
    place,
    note="",
    runnable_after=None,
):
    rows.append(
        {
            "id": id,
            "order": order,
            "role": role,
            "phase": phase,
            "data_condition": cond,
            "branch": branch,
            "depends_on": dep,
            "action": action,
            "steps": steps,
            "expected": expected,
            "status": "TODO",
            "evidence": "",
            # test-ladder L2: この行が流せるようになる条件 = 揃うべきタスク ID 群
            # (.claude/rules/common/test-ladder.md §3)。空 = 既存機能のみで流せる
            "runnable_after": list(
                runnable_after
                or RUNNABLE_AFTER.get(id)
                or RUNNABLE_AFTER.get(id.split("-")[0])
                or []
            ),
            "note": (f"場所={place}" + (f" / {note}" if note else "")),
        }
    )


def flow(prefix, role, place, base):
    """1 フロー分の行ビルダ。role / place は行ごとに上書きできる。"""

    def row(
        n,
        phase,
        cond,
        branch,
        dep,
        action,
        steps,
        expected,
        note="",
        role_=None,
        place_=None,
        order=None,
        runnable_after=None,
    ):
        R(
            f"{prefix}-{n:02d}",
            base + n if order is None else order,
            role_ or role,
            phase,
            cond,
            branch,
            list(dep),
            action,
            steps,
            expected,
            place_ or place,
            note,
            runnable_after,
        )

    return row


